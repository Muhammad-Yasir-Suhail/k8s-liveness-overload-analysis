def _job(args):
    kind, kw = args
    if kind == "R":
        cfg = repro_cfg(**kw)
    else:
        cfg = sut_cfg(**kw)
    r = simulate(cfg)
    r["_kw"] = json.dumps({k: v for k, v in kw.items() if k != "gov"})
    return r


def run(jobs, name, keep_series=False):
    with Pool() as p:
        rows = p.map(_job, jobs, chunksize=1)
    path = os.path.join(RES, name + ".csv")
    flat = []
    for r in rows:
        f = {k: v for k, v in r.items() if not k.endswith("_series")}
        flat.append(f)
    keys = sorted({k for f in flat for k in f})
    with open(path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=keys)
        w.writeheader()
        w.writerows(flat)
    if keep_series:
        with open(os.path.join(RES, name + "_series.json"), "w") as fh:
            json.dump([{"arm": r["arm"], "seed": r["seed"], "kw": r["_kw"],
                        "ratio": r["ratio_series"], "ready": r["ready_series"]} for r in rows], fh)
    print(f"  {name}: {len(rows)} runs -> {path}")
    return rows


def mean(xs):
    xs = [x for x in xs if x is not None and not (isinstance(x, float) and math.isnan(x))]
    return st.mean(xs) if xs else float("nan")


def sd(xs):
    xs = [x for x in xs if x is not None and not (isinstance(x, float) and math.isnan(x))]
    return st.pstdev(xs) if len(xs) > 1 else 0.0


def pick(rows, **cond):
    return [r for r in rows if all(r.get(k) == v for k, v in cond.items())]


def fmt(x, d=1):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    return f"{x:.{d}f}"


def pm(rows, key, d=1):
    v = [r[key] for r in rows]
    return f"{fmt(mean(v), d)} $\\pm$ {fmt(sd(v), d)}"


def macro(fh, name, val):
    fh.write(f"\\newcommand{{\\{name}}}{{{val}}}\n")



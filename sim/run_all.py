    fr = [mean([r["restarts_after_inject"] for r in WD if json.loads(r["_kw"])["window"] == w]) for w in Ws]
    ax.plot(Ws, det, color=COLOR["A"], marker="^", label="hang detection time (s)")
    ax.plot(Ws, fr, color=COLOR["FP"], marker="s", label="false restarts in 20 s stall")
    ax.set_xlabel("stall window W (s)")
    ax.set_xscale("log")
    ax.set_xticks(Ws, [str(w) for w in Ws])
    ax.legend(fontsize=7)
